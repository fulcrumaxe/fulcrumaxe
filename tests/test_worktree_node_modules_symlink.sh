#!/usr/bin/env bash
# tests/test_worktree_node_modules_symlink.sh
#
# Tests for D#689 PR-c: node_modules symlink creation in fresh worktrees.
#
# Tests:
#   1. spawn-agent.sh --isolation worktree --worktree-path creates tui/node_modules symlink
#   2. spawn-agent.sh --isolation worktree --worktree-path creates dashboard/node_modules symlink
#   3. Re-running when symlinks already exist is a no-op (idempotency)
#   4. Missing src dir (node_modules not present in main) is skipped gracefully
#
# Usage:
#   bash tests/test_worktree_node_modules_symlink.sh
# Exit code 0 = all tests passed.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SPAWN_SCRIPT="$REPO_ROOT/scripts/spawn-agent.sh"

PASS="[PASS]"
FAIL="[FAIL]"
INFO="[INFO]"

passed=0
failed=0

assert_true() {
  local desc="$1"; shift
  if "$@" 2>/dev/null; then
    echo "$PASS $desc"
    ((passed++)) || true
  else
    echo "$FAIL $desc"
    ((failed++)) || true
  fi
}

assert_eq() {
  local desc="$1"
  local got="$2"
  local want="$3"
  if [[ "$got" == "$want" ]]; then
    echo "$PASS $desc"
    ((passed++)) || true
  else
    echo "$FAIL $desc — got='$got' want='$want'"
    ((failed++)) || true
  fi
}

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# Create a fake main-like tree with tui/node_modules and dashboard/node_modules dirs.
# spawn-agent.sh uses REPO_ROOT which it derives from its own script path.
# We test the symlink logic by calling a sub-shell that sources just the
# symlink block, using env vars to override REPO_ROOT and WORKTREE_PATH_ARG.
_run_symlink_step() {
  local repo_root="$1"
  local worktree_path="$2"
  bash -c "
    REPO_ROOT=\"$repo_root\"
    WT_PATH=\"$worktree_path\"
    for _nm_dir in tui dashboard; do
      _nm_src=\"\$REPO_ROOT/\$_nm_dir/node_modules\"
      _nm_dst=\"\$WT_PATH/\$_nm_dir/node_modules\"
      if [ -d \"\$_nm_src\" ] && [ ! -e \"\$_nm_dst\" ]; then
        ln -s \"\$_nm_src\" \"\$_nm_dst\"
      fi
    done
  "
}

# ---------------------------------------------------------------------------
# Test 1 + 2: symlinks created for tui and dashboard
# ---------------------------------------------------------------------------
echo ""
echo "$INFO Test 1+2: node_modules symlinks created in fresh worktree"

FAKE_MAIN=$(mktemp -d)
FAKE_WT=$(mktemp -d)

mkdir -p "$FAKE_MAIN/tui/node_modules"
mkdir -p "$FAKE_MAIN/dashboard/node_modules"
mkdir -p "$FAKE_WT/tui"
mkdir -p "$FAKE_WT/dashboard"

_run_symlink_step "$FAKE_MAIN" "$FAKE_WT"

assert_true "tui/node_modules is a symlink" test -L "$FAKE_WT/tui/node_modules"
assert_true "dashboard/node_modules is a symlink" test -L "$FAKE_WT/dashboard/node_modules"

TUI_TARGET=$(readlink "$FAKE_WT/tui/node_modules" 2>/dev/null || echo "")
DASH_TARGET=$(readlink "$FAKE_WT/dashboard/node_modules" 2>/dev/null || echo "")
assert_eq "tui symlink points to main repo's tui/node_modules" "$TUI_TARGET" "$FAKE_MAIN/tui/node_modules"
assert_eq "dashboard symlink points to main repo's dashboard/node_modules" "$DASH_TARGET" "$FAKE_MAIN/dashboard/node_modules"

rm -rf "$FAKE_MAIN" "$FAKE_WT"

# ---------------------------------------------------------------------------
# Test 3: idempotency — re-running when symlinks exist is a no-op
# ---------------------------------------------------------------------------
echo ""
echo "$INFO Test 3: idempotency — existing symlinks are not changed"

FAKE_MAIN=$(mktemp -d)
FAKE_WT=$(mktemp -d)

mkdir -p "$FAKE_MAIN/tui/node_modules"
mkdir -p "$FAKE_MAIN/dashboard/node_modules"
mkdir -p "$FAKE_WT/tui"
mkdir -p "$FAKE_WT/dashboard"

# First run
_run_symlink_step "$FAKE_MAIN" "$FAKE_WT"

TUI_BEFORE=$(readlink "$FAKE_WT/tui/node_modules" 2>/dev/null || echo "")
DASH_BEFORE=$(readlink "$FAKE_WT/dashboard/node_modules" 2>/dev/null || echo "")

# Second run
_run_symlink_step "$FAKE_MAIN" "$FAKE_WT"

TUI_AFTER=$(readlink "$FAKE_WT/tui/node_modules" 2>/dev/null || echo "")
DASH_AFTER=$(readlink "$FAKE_WT/dashboard/node_modules" 2>/dev/null || echo "")

assert_eq "tui symlink unchanged after second run" "$TUI_BEFORE" "$TUI_AFTER"
assert_eq "dashboard symlink unchanged after second run" "$DASH_BEFORE" "$DASH_AFTER"

rm -rf "$FAKE_MAIN" "$FAKE_WT"

# ---------------------------------------------------------------------------
# Test 4: missing src dir is skipped (node_modules not present in main)
# ---------------------------------------------------------------------------
echo ""
echo "$INFO Test 4: missing src node_modules is skipped gracefully"

FAKE_MAIN=$(mktemp -d)
FAKE_WT=$(mktemp -d)

# Do NOT create node_modules in FAKE_MAIN — simulate an environment where
# npm install hasn't been run yet in the main repo.
mkdir -p "$FAKE_MAIN/tui"
mkdir -p "$FAKE_MAIN/dashboard"
mkdir -p "$FAKE_WT/tui"
mkdir -p "$FAKE_WT/dashboard"

SKIP_EXIT=0
_run_symlink_step "$FAKE_MAIN" "$FAKE_WT" || SKIP_EXIT=$?

assert_eq "script exits 0 when src dirs are absent" "$SKIP_EXIT" "0"
assert_true "tui/node_modules NOT created when src is absent" test ! -e "$FAKE_WT/tui/node_modules"
assert_true "dashboard/node_modules NOT created when src is absent" test ! -e "$FAKE_WT/dashboard/node_modules"

rm -rf "$FAKE_MAIN" "$FAKE_WT"

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
echo ""
echo "Results: $passed passed, $failed failed"
if [[ "$failed" -gt 0 ]]; then
  exit 1
fi
exit 0
